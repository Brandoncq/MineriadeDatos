/**
 * Función helper para obtener puntaje Minedu
 */
export const getMineduScore = (region, egresoYearStr, currentPostulaYear = 2025) => {
    const egresoYear = parseInt(egresoYearStr, 10);
    if (!region || isNaN(egresoYear)) return DEFAULT_MINEDU_SCORE;

    // Ajuste de año si sale del rango de datos
    let refYear = egresoYear;
    if (refYear >= 2024) refYear = 2024;
    else if (refYear < 2016) refYear = 2016; // Rango mínimo de tus datos

    const regionScores = MINEDU_SCORES_BY_REGION_AND_YEAR[region];
    return regionScores
        ? regionScores[refYear] || DEFAULT_MINEDU_SCORE
        : DEFAULT_MINEDU_SCORE;
};